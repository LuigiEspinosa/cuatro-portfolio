        'losers', 999, 'a');

-- ⭐⭐ THE RE-CROWN. A DIFFERENT entry, arriving on the FREE seat, asking to be crowned.
select ok(
  not public.match_place_competitor(
        (select id from match where tournament_id = pg_temp.tid('TALT') and bracket = 'losers' and bracket_slot = 900),
        'b', pg_temp.re('TALT', 2), true)
  and (select winner_entry from match
        where tournament_id = pg_temp.tid('TALT') and bracket = 'losers' and bracket_slot = 900)
      = pg_temp.re('TALT', 1),
  'AC1 (predicate) ⭐⭐ crowning a DIFFERENT entry on a walkover ALREADY WON returns FALSE and leaves winner_entry UNTOUCHED — AC1 guards the WINNER, not just the seat. Re-routing a decided match requires an explicit rollback first (AD-8 -> Story 4.7)');

-- The replay half: the SAME winner, re-crowned, is still SUCCESS. Idempotency must survive the new guard —
-- a fix that broke the replay would break AC1 from the other direction.
select ok(
  public.match_place_competitor(
    (select id from match where tournament_id = pg_temp.tid('TALT') and bracket = 'losers' and bracket_slot = 900),
    'a', pg_temp.re('TALT', 1), true)
  and (select winner_entry from match
        where tournament_id = pg_temp.tid('TALT') and bracket = 'losers' and bracket_slot = 900)
      = pg_temp.re('TALT', 1),
  'AC1 (predicate) ⭐ re-crowning the SAME winner is still TRUE and still idempotent — the new winner guard did not break the replay AC1 requires');

