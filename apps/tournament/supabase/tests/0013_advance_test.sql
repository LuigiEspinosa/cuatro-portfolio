-- Section L — AC1: THE PREDICATE ITSELF, in isolation (3)
-- ════════════════════════════════════════════════════════════════════════════
-- ⚠⚠ THIS SECTION EXISTS BECAUSE MUTATION TESTING FOUND THE SUITE COULD NOT SEE THE PREDICATE AT ALL.
-- Deleting the `WHERE slot IS NULL OR = winner` clause from match_place_competitor — i.e. deleting
-- ACCEPTANCE CRITERION 1 — left every other assertion in this file GREEN. The reason is structural:
-- `advance_match` validates the whole cascade under FOR UPDATE in pass 1, so by the time pass 2 calls the
-- helper the seat is already known to be free (or already ours), and the predicate never gets to decide
-- anything. It is a genuine belt-and-braces backstop — and an UNTESTED one, which is how a backstop
-- quietly stops working.
--
-- It is not dead code: the helper is GRANTED TO service_role, so Stories 4.5/4.6 can call it from inside
-- their own transactions WITHOUT pass 1 in front of it. Its contract is AC1's literal SQL
-- (SOLUTION-DESIGN §7 L357), so AC1 is asserted here directly, on the function that implements it.
set local role service_role;

-- An EMPTY seat accepts the entry. (winners/12 side a is still free — nothing has advanced into it.)
select ok(
  public.match_place_competitor(pg_temp.mid('TALT', 'winners', 12), 'a', pg_temp.re('TALT', 3), false),
  'AC1 (predicate): placing into an EMPTY seat returns true — `slot IS NULL` is the first half of the WHERE');

-- ⭐ THE SAME entry again: a REPLAY. `= winner` is the second half, and it is what makes a double-tap a
-- no-op rather than an error. row_count is still 1, so the caller sees SUCCESS, not a refusal.
select ok(
  public.match_place_competitor(pg_temp.mid('TALT', 'winners', 12), 'a', pg_temp.re('TALT', 3), false),
  'AC1 (predicate) ⭐ re-placing the SAME entry returns TRUE — `OR = winner` is what makes re-applying an advance a no-op instead of a failure');

-- ⭐⭐ A DIFFERENT entry: the seat is held, and the predicate REFUSES. This is the double-route AD-8
-- forbids, caught at the level of the single UPDATE that AC1 actually specifies.
select ok(
  not public.match_place_competitor(pg_temp.mid('TALT', 'winners', 12), 'a', pg_temp.re('TALT', 4), false)
  and pg_temp.comp('TALT', 'winners', 12, 'a') = pg_temp.re('TALT', 3),
  'AC1 (predicate) ⭐⭐ a DIFFERENT entry returns FALSE and does NOT overwrite the occupant — this is the no-double-route guarantee, asserted on the WHERE clause that provides it');

-- ════════════════════════════════════════════════════════════════════════════
-- Section M — AC1: THE PREDICATE MUST GUARD THE *WINNER*, NOT JUST THE SEAT (3)
-- ════════════════════════════════════════════════════════════════════════════
-- ⚠⚠⚠ THE 4.3 CODE REVIEW FOUND THAT SECTION L ABOVE STILL PROVED LESS THAN IT CLAIMED — all three of its
-- calls pass `p_walkover => false`, and `p_walkover => true` was the ONE mode in which the helper was
-- actually unsafe. Found independently by all three review layers and REPRODUCED as service_role:
--
--   The SET writes THREE columns (competitor_a, competitor_b, winner_entry) but the WHERE guarded only the
--   SEAT named by p_side. So crowning arrival Y on the FREE side of a bye node ALREADY WON by X passed the
--   predicate (that seat was empty), silently DEPOSED X, and returned TRUE. `match_winner_is_competitor`
--   did not catch it — Y is a competitor by the time the row settles. And `p_entry => NULL` (the shape a
--   caller trivially produces by passing a bye's non-existent loser) NULLED winner_entry outright and also
--   returned TRUE.
--
-- That is the exact double-route AC1 exists to prevent, performed by the function the story calls
-- "literally the AC". The mutation-testing exercise that produced Section L tested the PREDICATE and missed
-- the GUARD. These three assertions close it, on the function that is granted to service_role and that
-- 4.5/4.6 are explicitly told to call WITHOUT pass 1 in front of it.
--
-- A synthetic walkover node: state='bye', ALREADY WON by seed 1, side b free. (state='bye' is excluded from
-- match_live_requires_locked_format, so it needs no format — 0012:123-126.)
insert into match (tournament_id, bracket, bracket_position, bracket_slot, state,
